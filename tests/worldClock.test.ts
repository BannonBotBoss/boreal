import test from 'node:test'; import assert from 'node:assert/strict';
import { K } from '../src/core/constants';
import { hourAt, REAL_SECONDS_PER_GAME_HOUR } from '../src/core/timeOfDay';
import { CLOCK, DIAL_DEADZONE, clockRate, dialPosition, formatRate, groundWorldSec, isPaused, loadClock, nudgeDial, observation, offlineSec, pauseClock, resolveObservation, resumeClock, saveClock, setClockRate, simWorldSec, targetRate, targetRateFromDial, timeCommand, worldSec } from '../src/core/worldClock';
const near = (a: number, b: number, e = 1e-6) => assert.ok(Math.abs(a - b) <= e, `${a} vs ${b}`);
test('offline gap: forward only, capped', () => {
  assert.equal(offlineSec(1000, 61000), 60); assert.equal(offlineSec(61000, 1000), 0, 'clock set back');
  assert.equal(offlineSec(0, 1e13), CLOCK.maxOfflineSec, 'clock set far ahead'); assert.equal(offlineSec(NaN, 5), 0);
});
test('clock persists across quits; offline credits only a forwards capped gap', () => {
  loadClock(null, 0, 0); const r = clockRate();
  assert.equal(worldSec(0), 0); near(worldSec(5000), 5 * r);
  const raw = saveClock(10_000, 5000); const loaded = loadClock(raw, 70_000, 100);
  assert.equal(loaded.offlineSec, 60); near(worldSec(100), 5 * r + 60); near(worldSec(1100), 5 * r + 60 + r);
  assert.equal(loadClock(raw, 0, 0).offlineSec, 0, 'backwards wall clock credits nothing');
});
test('menu pause freezes the global clock; resume continues from the exact snapshot', () => {
  loadClock(null, 0, 0); const r = clockRate();
  near(worldSec(10_000), 10 * r); pauseClock(10_000); assert.ok(isPaused());
  assert.equal(worldSec(70_000), worldSec(100_000), 'frozen while menu is open');
  const frozen = worldSec(100_000);
  resumeClock(100_000); assert.ok(!isPaused()); near(worldSec(100_000), frozen); near(worldSec(101_000), frozen + r);
  pauseClock(101_000); pauseClock(102_000); assert.equal(worldSec(200_000), worldSec(102_000), 'pause is idempotent');
  const again = worldSec(200_000);
  resumeClock(200_000); resumeClock(200_000); near(worldSec(200_000), again); near(worldSec(201_000), again + r);
});
test('the dial is a power of ten from pause, and the old 16× cap is gone', () => {
  assert.equal(targetRateFromDial(0), 0);
  assert.equal(targetRateFromDial(0.009), 0);
  near(targetRateFromDial(0.1), 10 ** 1.2, 1e-9);
  near(targetRateFromDial(0.3), 10 ** 3.6, 1e-6);
  near(targetRateFromDial(0.5), 1e6, 1e-6);
  near(targetRateFromDial(1), 1e12, 1);
  near(targetRateFromDial(-0.5), -1e6, 1e-6);
  near(targetRateFromDial(DIAL_DEADZONE), 10 ** 0.12, 1e-9);
});
test('the in-game dial eases; it does not jump, and a big swing takes a few seconds', () => {
  loadClock(null, 0, 0);
  const rest = clockRate();
  timeCommand('faster', 0);
  assert.equal(clockRate(), rest, 'a notch moves the dial, not the rate');
  assert.ok(targetRate() > rest);
  worldSec(150);
  assert.ok(clockRate() > rest, 'the rate has started toward the notch');
  assert.ok(clockRate() < targetRate(), 'it has not arrived in one frame');
  nudgeDial(1 - dialPosition(), 150);
  assert.ok(Math.abs(targetRate() - 1e12) < 1);
  const atStart = clockRate();
  worldSec(650);
  assert.ok(clockRate() > atStart);
  assert.ok(clockRate() < 1e6, 'half a second does not leap to geological time');
  worldSec(8_000);
  assert.ok(clockRate() > 1e10, 'a few seconds later the rate is up at the top of the dial');
  assert.ok(clockRate() < 1e13, 'it does not run away past the dial');
  loadClock(null, 0, 0);
});
test('pause eases to a stop and play returns the dial; the menu hold is separate', () => {
  loadClock(null, 0, 0);
  nudgeDial(0.2, 0);
  const parked = dialPosition();
  timeCommand('pause', 0);
  assert.equal(dialPosition(), 0);
  assert.equal(isPaused(), false, 'pause eases; it does not freeze on the frame it is pressed');
  worldSec(3_000);
  assert.ok(isPaused(), 'a few seconds later the rate has settled on pause');
  assert.ok(Math.abs(clockRate()) < 1e-3);
  timeCommand('play', 3_000);
  near(dialPosition(), parked);
  pauseClock(3_000);
  timeCommand('play', 4_000);
  assert.equal(isPaused(), true, 'play does not release the menu hold');
  assert.equal(worldSec(5_000), worldSec(4_000));
  resumeClock(5_000);
  loadClock(null, 0, 0);
});
test('rewind moves the clock and the hour backward; ground and animals do not pretend to undo', () => {
  const h0 = hourAt(0), h1 = hourAt(-REAL_SECONDS_PER_GAME_HOUR);
  near((h0 - h1 + 24) % 24, 1, 1e-9);
  loadClock(null, 0, 0);
  setClockRate(-10, 0);
  near(clockRate(), -10, 1e-6);
  near(worldSec(1_000), -10, 1e-6);
  assert.equal(simWorldSec(-10), 0);
  assert.equal(groundWorldSec(-10), 0);
  assert.equal(groundWorldSec(4), 4);
  setClockRate(1e6, 0);
  assert.notEqual(observation().scale, 'immediate');
  assert.equal(simWorldSec(5), 0, 'above Immediate the animal step holds');
  setClockRate(4, 0);
  assert.equal(observation().scale, 'immediate');
  assert.equal(simWorldSec(2), 2);
  const raw = saveClock(0, 0);
  loadClock(raw, 0, 0);
  near(clockRate(), 4, 1e-6);
  loadClock(JSON.stringify({ worldSec: 3, wallMs: 0, rate: 1 }), 0, 0);
  near(clockRate(), targetRateFromDial(DIAL_DEADZONE), 1e-9);
  loadClock(null, 0, 0);
});
test('observation scale waits at the thresholds and the blend does not', () => {
  assert.equal(resolveObservation('immediate', 0).scale, 'immediate');
  assert.equal(resolveObservation('immediate', 10).scale, 'immediate');
  assert.ok(resolveObservation('immediate', 10).blend > 0 && resolveObservation('immediate', 10).blend < 1);
  assert.equal(resolveObservation('immediate', 12.1).scale, 'behavioral');
  assert.equal(resolveObservation('behavioral', 9).scale, 'behavioral');
  assert.equal(resolveObservation('behavioral', 7).scale, 'immediate');
  const mid = resolveObservation('behavioral', 1000);
  assert.equal(mid.scale, 'behavioral');
  assert.equal(mid.lower, 'behavioral');
  assert.equal(mid.higher, 'ecological');
  near(mid.blend, 0.5, 1e-9);
  assert.equal(resolveObservation('ecological', 1000).scale, 'ecological');
  assert.equal(resolveObservation('ecological', 799).scale, 'behavioral');
  assert.equal(resolveObservation('geological', 1.2e11 + 1).scale, 'planetary');
  assert.equal(resolveObservation('planetary', 9e10).scale, 'planetary');
  assert.equal(resolveObservation('planetary', 7e10).scale, 'geological');
});
test('the bar can read the rate in world time per real second', () => {
  assert.equal(formatRate(0), 'paused');
  assert.equal(formatRate(3600), '1 hour / sec');
  assert.equal(formatRate(-3600), '−1 hour / sec');
  assert.equal(formatRate(1000 * K.julian_year_s), '1,000 years / sec');
  assert.equal(formatRate(K.julian_year_s), '1 year / sec');
});
