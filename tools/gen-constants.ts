// Generate rust/boreal-sim/src/constants.rs from src/data/constants.json (locked values). Run: npx tsx tools/gen-constants.ts
// tests/constants.test.ts fails if the committed file is stale.
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { BASE, DERIVED, MATH, evaluate } from '../src/core/constants';

export function rustSource() {
  const v = evaluate();
  const line = (n: string, note: string) => `pub const ${n}: f64 = ${v[n].toExponential(16)}; // ${note}`;
  return ['//! GENERATED by tools/gen-constants.ts from src/data/constants.json. Do not edit. Locked (CODATA/IAU) values.', '#![allow(non_upper_case_globals)]', '',
    ...Object.keys(MATH).map(n => line(n, 'math')),
    ...Object.entries(BASE).map(([n, b]) => line(n, `${b.unit}; ${b.source}`)),
    ...Object.entries(DERIVED).map(([n, d]) => line(n, `${d.unit}; = ${d.formula}`)), ''].join('\n');
}
if (process.argv[1]?.endsWith('gen-constants.ts'))
  writeFileSync(join(import.meta.dirname, '..', 'rust', 'boreal-sim', 'src', 'constants.rs'), rustSource());
